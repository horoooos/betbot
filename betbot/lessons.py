def rubrics() -> list[str]:
    seen = []
    for x in L:
        if x["rubric"] not in seen:
            seen.append(x["rubric"])
    return seen


def next_lesson(used: list[str]) -> dict:
    """Следующий ликбез: рубрики по очереди, без повторов, пока не пройдён весь банк (потом — заново)."""
    if all(x["title"] in used for x in L):
        used.clear()
    last = next((x["rubric"] for x in reversed(L) if x["title"] == (used[-1] if used else None)), None)
    order = rubrics()
    start = (order.index(last) + 1) % len(order) if last in order else 0
    for k in range(len(order)):
        rub = order[(start + k) % len(order)]
        for x in L:
            if x["rubric"] == rub and x["title"] not in used:
                return x
    return L[0]
