def clean(text):
    text=re.sub(r'(?im)^\s*/humanize\s*(?:\n|$)','',str(text)).strip()
    text=re.sub(r'\A(?:Вот (?:более человечный|переписанный|отредактированный) (?:вариант|текст):)\s*','',text,flags=re.I)
    return re.sub(r'\n{3,}','\n\n',text).strip()
