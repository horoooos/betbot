"""Natural Russian editorial style; facts and numeric checks stay separate."""
import re

HUMANIZE_STYLE = (
    "Редакторский режим /humanize. Пиши естественным русским языком: как внимательный спортивный редактор, "
    "который понятно рассказывает новость знакомому читателю. Сразу сообщи главный факт. "
    "Чередуй короткие и средние предложения, используй обычные глаголы и конкретные детали. "
    "Сохрани все существенные факты исходника, счёт, даты, имена и оговорки. "
    "Не растягивай короткую новость до заданного объёма и не сокращай содержательную статью до одной фразы. "
    "Делай отдельный абзац для каждой мысли, между абзацами оставляй пустую строку. "
    "Не начинай каждый абзац эмодзи: достаточно 0–3 уместных эмодзи на весь текст. "
    "Без обязательного кликбейта, фальшивой сенсации, рекламного тона и выдуманных эмоций. "
    "Избегай шаблонов «шок», «взорвал интернет», «никого не оставил равнодушным», «стоит отметить», "
    "«это событие подчёркивает», «в современном мире». Не добавляй вывод ради вывода и вопрос читателю ради охватов. "
    "Не изображай очевидца, не придумывай инсайды, статистику, чужие слова или собственный опыт. "
    "Команда /humanize и редакторские пояснения в готовый текст не попадают. "
)

def clean(text):
    text=re.sub(r'(?im)^\s*/humanize\s*(?:\n|$)','',str(text)).strip()
    text=re.sub(r'\A(?:Вот (?:более человечный|переписанный|отредактированный) (?:вариант|текст):)\s*','',text,flags=re.I)
    return re.sub(r'\n{3,}','\n\n',text).strip()
