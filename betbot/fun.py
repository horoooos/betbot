"""Оформление, чтобы канал было интересно читать: шкалы шансов, уверенность, живые фразы в итогах."""
import random

WIN = ["Касса! 💰", "Так и задумано 😎", "Ещё один в копилку 🧺", "Чистая работа 🧹", "Бот снова в деле 🤖",
       "Как по нотам 🎼", "Записываем в плюс ✍️", "Уверенно и без нервов 🧊"]
LOSS = ["Бывает и так — работаем дальше 💪", "Спорт непредсказуем — на дистанции решает математика 📐",
        "Не наш день, отыграемся 🔄", "Минус в копилку опыта: бот учтёт это в калибровке 🧠",
        "Обидно, но без паники — играем по системе 🧘"]


def bar(p: float, n: int = 10) -> str:
    """▰▰▰▰▰▱▱▱▱▱ — шкала вероятности."""
    k = max(0, min(n, round(p * n)))
    return "▰" * k + "▱" * (n - k)


def chances(rows: list[tuple[str, float]]) -> str:
    """Блок «📊 Шансы» с шкалой для каждого исхода (нулевые — ничья в теннисе/баскетболе — пропускаем)."""
    rows = [(n, p) for n, p in rows if p > 0.005]
    width = max(len(n) for n, _ in rows)
    return "📊 <b>Шансы по модели</b>\n<code>" + "\n".join(
        f"{n.ljust(width)} {bar(p)} {100 * p:.0f}%" for n, p in rows) + "</code>"


def confidence(p: float) -> str:
    if p >= 0.72:
        return "🟢 Уверенность: <b>высокая</b>"
    if p >= 0.58:
        return "🟡 Уверенность: <b>средняя</b>"
    return "🟠 Уверенность: <b>умеренная</b> — ставка с риском"


def verdict(hit) -> str:
    return f"\n<i>{random.choice(WIN if hit else LOSS)}</i>"
